"""Build the Agent OS Firefox extension.

    python browser/extension/tools/build.py            # dist/agent-os-firefox/ + unsigned .xpi
    python browser/extension/tools/build.py --sign     # also sign through AMO (unlisted)
    python browser/extension/tools/build.py --sign --publish --install
        # --publish copies the signed .xpi + updates.json into the public
        # unwit1/universal-capture-plugin clone (firefox/), commits and pushes;
        # installed copies then auto-update through manifest update_url.
    python browser/extension/tools/build.py --sign --install
        # ...and drop the signed .xpi into the default Firefox profile; Firefox
        # picks the new version up on its next start (no prompt), and an
        # update prompt is opened in the running Firefox right away.

The Universal Capture userscript stays the single source for capture code:
it is wrapped into content/capture.generated.js at build time and runs on the
GM_* shim. Signing uses AMO API credentials from the environment
(WEB_EXT_API_KEY / WEB_EXT_API_SECRET) or the Windows Credential Manager
(service "agent-os-amo", users "api_key" and "api_secret").
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

EXT_DIR = Path(__file__).resolve().parents[1]
SRC_DIR = EXT_DIR / "src"
DIST_DIR = EXT_DIR / "dist"
OUT_DIR = DIST_DIR / "agent-os-firefox"
USERSCRIPT = EXT_DIR.parent / "userscripts" / "agent-os-universal-capture.user.js"
GENERATED = Path("content") / "capture.generated.js"

# Userscript wording that would be wrong inside the extension.
TEXT_REPLACEMENTS = [
    ("the Tampermonkey menu", "the Agent OS toolbar menu"),
    ("Tampermonkey menu", "Agent OS toolbar menu"),
    ("Tampermonkey storage", "extension storage"),
]


def wrap_userscript(source: str) -> str:
    marker = "// ==/UserScript=="
    index = source.find(marker)
    if index == -1:
        raise SystemExit("userscript metadata block not found")
    body = source[index + len(marker):].lstrip("\r\n")
    for old, new in TEXT_REPLACEMENTS:
        body = body.replace(old, new)
    return (
        "// GENERATED by browser/extension/tools/build.py from\n"
        "// browser/userscripts/agent-os-universal-capture.user.js. Do not edit.\n"
        "var __AGENT_OS_EXTENSION__ = true;\n"
        "globalThis.__agentOsGmReady.then(function () {\n"
        f"{body}\n"
        "}).catch(function (error) { console.error('[Agent OS] capture failed to start', error); });\n"
    )


def build() -> Path:
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    shutil.copytree(SRC_DIR, OUT_DIR)
    generated = OUT_DIR / GENERATED
    generated.write_text(wrap_userscript(USERSCRIPT.read_text(encoding="utf-8")), encoding="utf-8")

    manifest = json.loads((OUT_DIR / "manifest.json").read_text(encoding="utf-8"))
    for group in manifest["content_scripts"]:
        for script in group["js"]:
            if not (OUT_DIR / script).exists():
                raise SystemExit(f"manifest references missing file: {script}")
    version = manifest["version"]
    xpi = DIST_DIR / f"agent-os-firefox-{version}.xpi"
    with zipfile.ZipFile(xpi, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(OUT_DIR.rglob("*")):
            if path.is_file():
                archive.write(path, path.relative_to(OUT_DIR).as_posix())
    return xpi


EXTENSION_ID = "agent-os@unwit1.local"


def default_firefox_profile() -> Path | None:
    """The profile Firefox opens by default (profiles.ini [Install*] Default=)."""
    import configparser

    root = Path(os.environ.get("APPDATA", "")) / "Mozilla" / "Firefox"
    ini = configparser.ConfigParser()
    if not ini.read(root / "profiles.ini", encoding="utf-8"):
        return None
    for section in ini.sections():
        if section.startswith("Install") and ini.get(section, "Default", fallback=""):
            path = Path(ini.get(section, "Default"))
            return path if path.is_absolute() else root / path
    for section in ini.sections():
        if ini.get(section, "Default", fallback="") == "1" and ini.get(section, "Path", fallback=""):
            path = Path(ini.get(section, "Path"))
            relative = ini.get(section, "IsRelative", fallback="1") == "1"
            return root / path if relative else path
    return None


def install(signed: Path) -> dict:
    profile = default_firefox_profile()
    if not profile or not profile.exists():
        raise SystemExit("could not find the default Firefox profile")
    target = profile / "extensions" / f"{EXTENSION_ID}.xpi"
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_suffix(".xpi.tmp")
    shutil.copyfile(signed, temp)
    try:
        os.replace(temp, target)
        where = str(target)
    except PermissionError:
        # A running Firefox locks the installed file; stage the update so
        # Firefox applies it on its next start.
        temp.unlink(missing_ok=True)
        staged = profile / "extensions" / "staged" / f"{EXTENSION_ID}.xpi"
        staged.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(signed, staged)
        where = str(staged) + " (staged until Firefox restarts)"
    firefox = Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Mozilla Firefox" / "firefox.exe"
    opened = False
    if firefox.exists():
        subprocess.Popen([str(firefox), str(signed)], close_fds=True)
        opened = True
    return {"installed_to": where, "update_prompt_opened": opened}


def install_restart(signed: Path) -> dict:
    """Install without a prompt: close Firefox, put the signed build in the profile, start Firefox.

    Firefox is force-closed so its crash recovery restores every window and tab
    (a normal close restores only the last window). Clearing addonStartup.json.lz4
    makes Firefox re-read the replaced extension file on startup. Only use this
    between browser jobs: open pages are reloaded.
    """
    import time
    profile = default_firefox_profile()
    if not profile or not profile.exists():
        raise SystemExit("could not find the default Firefox profile")
    firefox = Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Mozilla Firefox" / "firefox.exe"
    time.sleep(16)  # let session store write a fresh recovery file
    subprocess.run(["taskkill", "/F", "/IM", "firefox.exe"], capture_output=True)
    time.sleep(4)
    shutil.copyfile(signed, profile / "extensions" / f"{EXTENSION_ID}.xpi")
    (profile / "extensions" / "staged" / f"{EXTENSION_ID}.xpi").unlink(missing_ok=True)
    (profile / "addonStartup.json.lz4").unlink(missing_ok=True)
    prefs = profile / "prefs.js"
    current = prefs.read_text(encoding="utf-8", errors="replace")
    lines = [
        # Repeated forced restarts still restore every window automatically.
        'user_pref("browser.sessionstore.max_resumed_crashes", 3);',
        # Keep rendering Agent OS windows that are covered by other windows (ADP's pages stall otherwise).
        'user_pref("widget.windows.window_occlusion_tracking.enabled", false);',
    ]
    with open(prefs, "a", encoding="utf-8") as fh:
        for line in lines:
            if line not in current:
                fh.write(line + "\n")
    subprocess.Popen([str(firefox)], close_fds=True)
    return {"installed": signed.name, "profile": str(profile), "firefox_restarted": True}


def latest_signed(version: str) -> Path | None:
    candidates = sorted((DIST_DIR / "signed").glob(f"*-{version}.xpi"), key=lambda p: p.stat().st_mtime)
    return candidates[-1] if candidates else None


PUBLIC_REPO = EXT_DIR.parents[2] / "universal-capture-plugin"
PUBLIC_RAW = "https://raw.githubusercontent.com/unwit1/universal-capture-plugin/main/firefox/"
COMMIT_TRAILER = "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def publish(signed: Path, version: str) -> dict:
    import hashlib

    repo = Path(os.environ.get("AOS_PUBLIC_REPO", PUBLIC_REPO))
    if not (repo / ".git").exists():
        raise SystemExit(f"public repo clone not found at {repo}")
    git(repo, "pull", "--rebase", "--autostash", "--quiet")
    dest = repo / "firefox"
    dest.mkdir(exist_ok=True)
    name = f"agent-os-firefox-{version}.xpi"
    shutil.copyfile(signed, dest / name)
    digest = hashlib.sha256((dest / name).read_bytes()).hexdigest()
    # Keep the three newest builds so a bad release can be rolled back.
    builds = sorted(dest.glob("agent-os-firefox-*.xpi"),
                    key=lambda p: [int(x) for x in p.stem.rsplit("-", 1)[1].split(".")])
    for old in builds[:-3]:
        old.unlink()
    updates = {"addons": {EXTENSION_ID: {"updates": [{
        "version": version,
        "update_link": PUBLIC_RAW + name,
        "update_hash": "sha256:" + digest,
        "applications": {"gecko": {"strict_min_version": "140.0"}},
    }]}}}
    (dest / "updates.json").write_text(json.dumps(updates, indent=2) + chr(10), encoding="utf-8")
    git(repo, "add", "-A", "firefox")
    if not git(repo, "diff", "--cached", "--name-only", "--", "firefox").strip():
        return {"published": False, "reason": "no changes"}
    git(repo, "commit", "-q", "-m", f"Publish Agent OS Firefox extension {version}" + chr(10) * 2 + COMMIT_TRAILER, "--", "firefox")
    git(repo, "push", "-q")
    return {"published": True, "version": version, "update_link": PUBLIC_RAW + name, "sha256": digest}


def amo_credentials() -> tuple[str, str]:
    key = os.environ.get("WEB_EXT_API_KEY", "")
    secret = os.environ.get("WEB_EXT_API_SECRET", "")
    if key and secret:
        return key, secret
    try:
        import keyring

        key = keyring.get_password("agent-os-amo", "api_key") or ""
        secret = keyring.get_password("agent-os-amo", "api_secret") or ""
    except Exception:
        pass
    return key, secret


def sign() -> int:
    key, secret = amo_credentials()
    if not (key and secret):
        print(
            "No AMO API credentials. Create them at https://addons.mozilla.org/developers/addon/api/key/ "
            "and store them with:\n"
            '  python -c "import keyring; keyring.set_password(\'agent-os-amo\', \'api_key\', input(\'JWT issuer: \'))"\n'
            '  python -c "import keyring, getpass; keyring.set_password(\'agent-os-amo\', \'api_secret\', getpass.getpass(\'JWT secret: \'))"',
            file=sys.stderr,
        )
        return 2
    env = dict(os.environ, WEB_EXT_API_KEY=key, WEB_EXT_API_SECRET=secret)
    command = [
        "npx", "--yes", "web-ext@8", "sign",
        "--source-dir", str(OUT_DIR),
        "--artifacts-dir", str(DIST_DIR / "signed"),
        "--channel", "unlisted",
    ]
    return subprocess.call(command, env=env, shell=os.name == "nt")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sign", action="store_true", help="sign the build through AMO (unlisted channel)")
    parser.add_argument("--publish", action="store_true", help="publish the signed build + updates.json to the public repo")
    parser.add_argument("--install", action="store_true", help="install the signed build into the default Firefox profile")
    parser.add_argument("--install-restart", action="store_true",
                        help="install with no prompt by restarting Firefox (tabs are restored); use between browser jobs")
    args = parser.parse_args()
    xpi = build()
    print(json.dumps({"unpacked": str(OUT_DIR), "xpi": str(xpi)}, indent=2))
    if args.sign:
        code = sign()
        if code:
            return code
    if args.publish or args.install or args.install_restart:
        version = json.loads((OUT_DIR / "manifest.json").read_text(encoding="utf-8"))["version"]
        signed = latest_signed(version)
        if not signed:
            raise SystemExit(f"no signed build for {version}; run with --sign")
        if args.publish:
            print(json.dumps(publish(signed, version), indent=2))
        if args.install_restart:
            print(json.dumps(install_restart(signed), indent=2))
        elif args.install:
            print(json.dumps(install(signed), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
