"""Stable, machine-local launcher for the Agent OS MCP server.

An MCP client registration should not embed a repository checkout path, because
moving or recloning the repository then silently breaks the integration. Clients
point at a launcher in the user's home directory; the launcher resolves the
current checkout and serves the repository's own entry point in-process.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import threading
import time
from pathlib import Path
from typing import Any

from .paths import ROOT


LAUNCHER_DIR = Path.home() / ".agent-os"
LAUNCHER_PATH = LAUNCHER_DIR / "agent_os_mcp_launcher.py"
CONFIG_PATH = LAUNCHER_DIR / "config.json"

LAUNCHER_SOURCE = '''#!/usr/bin/env python3
"""Stable launcher for the Personal Agent OS MCP server.

Generated by `agent-os launcher-install`. Edit the repository template, not this
file. The MCP client registration points here so the checkout can move.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

CONFIG_PATH = Path(__file__).resolve().parent / "config.json"
HOME_ROOTS = ("GitHub", "Projects", "repos", "source/repos", "dev")
CANONICAL_DIRECTORY = "personal-agent-os"


def _is_checkout(path: Path) -> bool:
    return (path / "agent.py").is_file() and (path / "src" / "agent_os").is_dir()


def _configured() -> Path | None:
    try:
        config = json.loads(CONFIG_PATH.read_text(encoding="utf-8-sig"))
    except (OSError, json.JSONDecodeError):
        return None
    value = config.get("repository_path")
    if not value:
        return None
    path = Path(value).expanduser()
    return path if _is_checkout(path) else None


def _discover() -> Path | None:
    """Survive a repository move without reinstalling the client registration.

    Several checkouts of this repository may exist on one machine, so the
    canonically named directory wins before any other checkout is considered.
    """
    roots = [Path.home() / item for item in HOME_ROOTS]
    for root in roots:
        candidate = root / CANONICAL_DIRECTORY
        if _is_checkout(candidate):
            return candidate
    for root in roots:
        try:
            entries = sorted(item for item in root.iterdir() if item.is_dir())
        except OSError:
            continue
        for entry in entries:
            if _is_checkout(entry):
                return entry
    return None


def main() -> None:
    """Serve in this process, never in a replacement one.

    os.execv does not replace the process image on Windows: it starts a second
    process and exits the first. An MCP client watching the process it spawned
    then sees it terminate during the handshake while the inherited pipes stay
    open, and waits on a server it believes is already dead until its timeout.
    Importing the CLI keeps one process on the client's stdio for the session.
    """
    repo = _configured() or _discover()
    if repo is None:
        raise SystemExit(
            "Agent OS checkout not found. Run `python agent.py launcher-install` "
            f"from the repository to refresh {CONFIG_PATH}."
        )
    os.chdir(repo)
    sys.path.insert(0, str(repo / "src"))
    from agent_os.cli import main as cli_main

    raise SystemExit(cli_main(["mcp"]))


if __name__ == "__main__":
    main()
'''


def _config(repository_path: Path) -> dict[str, Any]:
    return {
        "schema_version": 1,
        "repository_path": str(repository_path),
        "installed_by": "agent-os launcher-install",
        "canonical_repository": "https://github.com/unwit1/personal-agent-os",
    }


def install(repository_path: Path | None = None) -> dict[str, Any]:
    repository = (repository_path or ROOT).resolve()
    LAUNCHER_DIR.mkdir(parents=True, exist_ok=True)
    LAUNCHER_PATH.write_text(LAUNCHER_SOURCE, encoding="utf-8", newline="\n")
    CONFIG_PATH.write_text(
        json.dumps(_config(repository), indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    return {
        "launcher": str(LAUNCHER_PATH),
        "config": str(CONFIG_PATH),
        "repository_path": str(repository),
        "registration_command": f"{sys.executable} {LAUNCHER_PATH}",
    }


def status() -> dict[str, Any]:
    installed = LAUNCHER_PATH.exists()
    current = installed and LAUNCHER_PATH.read_text(encoding="utf-8") == LAUNCHER_SOURCE
    configured: str | None = None
    if CONFIG_PATH.exists():
        try:
            configured = json.loads(CONFIG_PATH.read_text(encoding="utf-8-sig")).get("repository_path")
        except (OSError, json.JSONDecodeError):
            configured = None
    resolved = Path(configured).expanduser() if configured else None
    return {
        "launcher": str(LAUNCHER_PATH),
        "installed": installed,
        "matches_template": current,
        "config": str(CONFIG_PATH),
        "configured_repository_path": configured,
        "configured_path_is_checkout": bool(
            resolved and (resolved / "agent.py").is_file() and (resolved / "src" / "agent_os").is_dir()
        ),
        "current_repository_path": str(ROOT),
        "registration_command": f"{sys.executable} {LAUNCHER_PATH}",
    }


def verify(timeout: int = 60) -> dict[str, Any]:
    """Drive a real MCP handshake through the launcher in a separate process.

    The client's own process is the unit under test, not just the bytes on the
    pipe. A launcher that hands the session to a second process and exits looks
    healthy to a reader that only drains stdout to EOF, but an MCP client
    watching the child it spawned sees that exit as the server dying. So the
    process is held open across the whole handshake and its liveness checked
    while responses are still expected.
    """
    if not LAUNCHER_PATH.exists():
        return {"ok": False, "reason": f"launcher is not installed at {LAUNCHER_PATH}"}
    requests = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {"protocolVersion": "2025-06-18", "capabilities": {}, "clientInfo": {"name": "agent-os-verify", "version": "0"}}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
        {"jsonrpc": "2.0", "id": 3, "method": "tools/call", "params": {"name": "agent.project_status", "arguments": {"project_hint": "personal-agent-os"}}},
    ]
    process = subprocess.Popen(
        [sys.executable, str(LAUNCHER_PATH)],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
    )
    responses: list[dict[str, Any]] = []
    stayed_alive = True
    reason: str | None = None
    deadline = time.monotonic() + timeout
    reader: list[str] = []

    def _pump() -> None:
        assert process.stdout is not None
        for line in process.stdout:
            reader.append(line)

    pump = threading.Thread(target=_pump, daemon=True)
    pump.start()
    try:
        assert process.stdin is not None
        for request in requests:
            process.stdin.write(json.dumps(request) + "\n")
            process.stdin.flush()
        # Every response must arrive while the spawned process is still the
        # one serving them, exactly as a long-lived client requires.
        while time.monotonic() < deadline:
            if len(reader) >= 3:
                break
            if process.poll() is not None:
                stayed_alive = False
                reason = (
                    "the spawned launcher process exited with code "
                    f"{process.returncode} before the handshake completed; an MCP "
                    "client watching that process treats this as server death"
                )
                break
            time.sleep(0.05)
        else:
            reason = "launcher did not complete the handshake in time"
        if stayed_alive and process.poll() is not None:
            stayed_alive = False
            reason = reason or "the spawned launcher process exited during the handshake"
    except OSError as error:  # pragma: no cover - platform dependent
        reason = f"could not drive the launcher: {error}"
    finally:
        still_running = process.poll() is None
        try:
            if process.stdin is not None:
                process.stdin.close()
        except OSError:
            pass
        pump.join(timeout=5)
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:  # pragma: no cover - defensive
            process.kill()
            process.wait(timeout=10)
        stderr = (process.stderr.read() if process.stderr else "") or ""
        if process.stderr is not None:
            process.stderr.close()
        if process.stdout is not None:
            process.stdout.close()

    for line in reader:
        try:
            responses.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    by_id = {item.get("id"): item for item in responses}
    server_name = by_id.get(1, {}).get("result", {}).get("serverInfo", {}).get("name")
    tools = {tool["name"] for tool in by_id.get(2, {}).get("result", {}).get("tools", [])}
    called = by_id.get(3, {}).get("result", {})
    ok = (
        stayed_alive
        and still_running
        and server_name == "personal-agent-os"
        and "agent.context" in tools
        and called.get("isError") is False
        and 2 not in {item.get("id") for item in responses if "error" in item}
    )
    return {
        "ok": ok,
        "served_in_spawned_process": stayed_alive and still_running,
        "reason": None if ok else (reason or "handshake did not produce the expected responses"),
        "server_name": server_name,
        "tool_count": len(tools),
        "notification_produced_response": None in by_id and by_id[None].get("error") is None,
        "tool_call_ok": called.get("isError") is False,
        "stderr": stderr.strip()[:500] or None,
    }
